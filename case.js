// **Task 2.1 — Case Conversion**

let name = "JavaScript";
// Print the uppercase version.
let nameUppercaseVersion = name.toUpperCase();
console.log(nameUppercaseVersion);


// Print the lowercase version.
let nameLowercaseVersion = name.toLowerCase();
console.log(nameLowercaseVersion);


